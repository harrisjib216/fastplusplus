#!/usr/bin/env python3
"""Compile data/seeds/no_evidence/*.json (projects a backfill agent found no numeric baseline
comparison for) into catalog/seeds-no-evidence.md (docs/QUEUE.md section F, rule 4)."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "data" / "seeds" / "no_evidence"
OUT = ROOT / "catalog" / "seeds-no-evidence.md"


def main():
    rows, bad = {}, []
    for f in sorted(SRC.glob("*.json")):
        try:
            items = json.loads(f.read_text())
        except json.JSONDecodeError as err:
            bad.append(f"{f.name}: {err}"); continue
        for it in items if isinstance(items, list) else []:
            if not isinstance(it, dict) or not it.get("repo_url"):
                continue
            key = it["repo_url"].rstrip("/").lower()
            it["assignment"] = f.stem
            rows.setdefault(key, it)
    lines = ["# Seeds without evidence",
             "",
             "<sub>[fastpp](../README.md) › [Catalog](README.md)</sub>",
             "",
             "Projects mined from curated lists (see `data/seeds/seeds.json`) for which a backfill seed-record agent",
             "found no numeric comparison against any recognisable baseline. They are not catalogued; they are kept",
             "here so a later wave or a human can revisit them. Generated by `pipeline/seeds_no_evidence.py`.",
             "",
             f"{len(rows)} projects.",
             "",
             "| Project | Repository | Listed as | Why no record | Pass |",
             "|---|---|---|---|---|"]
    for key, it in sorted(rows.items(), key=lambda kv: str(kv[1].get("name", "")).lower()):
        esc = lambda s: str(s or "").replace("|", "\\|").replace("\n", " ")
        lines.append(f"| {esc(it.get('name'))} | {esc(it.get('repo_url'))} | {esc(it.get('listed_description'))} | {esc(it.get('reason'))} | {esc(it.get('assignment'))} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} no-evidence seeds -> {OUT.name}" + (f"; invalid files: {bad}" if bad else ""))


if __name__ == "__main__":
    main()
