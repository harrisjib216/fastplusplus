// Compiles data/seeds/no_evidence/*.json (projects a backfill agent found no numeric baseline comparison for) into
// catalog/seeds-no-evidence.md (docs/QUEUE.md section F, rule 4).
#include <algorithm>
#include <iostream>
#include <set>

#include "json.hpp"
#include "render.hpp"
#include "text.hpp"

namespace fs = std::filesystem;
using json::Value;

namespace {

std::string text_of(const Value& value) { return value.truthy() ? json::str(value) : std::string(); }

std::string esc(const Value& value) {
    return text::replace_all(text::replace_all(text_of(value), "|", "\\|"), "\n", " ");
}

}  // namespace

int render_seeds(const Catalog& catalog) {
    fs::path source = catalog.data / "seeds" / "no_evidence";
    fs::path out = catalog.root / "catalog" / "seeds-no-evidence.md";

    // A book companion repo carries several techniques: keep one row per technique, not per repo.
    std::set<std::string> companions;
    for (const Value& seed : json::parse(read_file(catalog.data / "seeds" / "seeds.json")).array) {
        const Value& kind = seed.get("kind");
        if (kind.is_string() && kind.text == "book-companion") {
            companions.insert(text::lower(text::rstrip_chars(seed.get("repo_url").text, "/")));
        }
    }

    std::vector<fs::path> files;
    if (fs::is_directory(source)) {
        for (const auto& item : fs::directory_iterator(source)) {
            if (item.path().extension() == ".json") files.push_back(item.path());
        }
    }
    std::sort(files.begin(), files.end());

    std::vector<std::pair<std::string, Value>> rows;
    std::set<std::string> keys;
    std::vector<std::string> bad;
    for (const fs::path& file : files) {
        Value items;
        try {
            items = json::parse(read_file(file));
        } catch (const json::Error& error) {
            bad.push_back(file.filename().string() + ": " + error.message);
            continue;
        }
        if (!items.is_array()) continue;
        for (Value& item : items.array) {
            if (!item.is_object() || !item.get("repo_url").truthy()) continue;
            std::string repo_url = json::str(item.get("repo_url"));
            std::string key = text::lower(text::rstrip_chars(repo_url.substr(0, repo_url.find('#')), "/"));
            if (companions.count(key) || repo_url.find('#') != std::string::npos) {
                key += "#" + text::lower(text_of(item.get("name")));
            }
            item.set("assignment", Value::of(file.stem().string()));
            if (keys.insert(key).second) rows.emplace_back(key, std::move(item));
        }
    }

    auto sort_name = [](const Value& item) {
        const Value* name = item.find("name");
        return text::lower(name ? json::str(*name) : "");
    };
    std::stable_sort(rows.begin(), rows.end(), [&](const auto& a, const auto& b) { return sort_name(a.second) < sort_name(b.second); });

    std::string page =
        "# Seeds without evidence\n"
        "\n"
        "<sub>[fastpp](../README.md) › [Catalog](README.md)</sub>\n"
        "\n"
        "Projects mined from curated lists (see `data/seeds/seeds.json`) for which a backfill seed-record agent\n"
        "found no numeric comparison against any recognisable baseline. They are not catalogued; they are kept\n"
        "here so a later wave or a human can revisit them. Generated by `fastpp seeds` (`src/seeds.cpp`).\n"
        "\n"
        + std::to_string(rows.size()) + " projects.\n"
        "\n"
        "| Project | Repository | Listed as | Why no record | Pass |\n"
        "|---|---|---|---|---|\n";
    for (const auto& [_, item] : rows) {
        page += "| " + esc(item.get("name")) + " | " + esc(item.get("repo_url")) + " | " + esc(item.get("listed_description")) + " | "
            + esc(item.get("reason")) + " | " + esc(item.get("assignment")) + " |\n";
    }
    write_file(out, page);

    std::cout << rows.size() << " no-evidence seeds -> " << out.filename().string();
    if (!bad.empty()) {
        std::cout << "; invalid files:";
        for (const std::string& b : bad) std::cout << " " << b;
    }
    std::cout << "\n";
    return 0;
}
